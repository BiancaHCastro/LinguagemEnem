def avaliar_cv(nome_modelo, construtor_fn, config_str, hipotese):
    print(f"\n>>> Avaliando em CV ({len(splits_cv)} dobras): {nome_modelo}")
    metricas_dobras = []

    for dobra, (idx_tr, idx_va) in enumerate(splits_cv, start=1):
        X_tr, y_tr = X_dev.iloc[idx_tr], y_dev[idx_tr]
        X_va, y_va = X_dev.iloc[idx_va], y_dev[idx_va]

        pipe = construtor_fn()
        t0 = time.perf_counter()
        pipe.fit(X_tr, y_tr)
        t_treino = time.perf_counter() - t0

        t1 = time.perf_counter()
        pred_va = pipe.predict(X_va)
        t_pred = time.perf_counter() - t1

        m = calcular_metricas(y_va, pred_va)
        linha = {
            "etapa": "cv_dobra",
            "modelo": nome_modelo,
            "dobra_ou_grupo": f"dobra_{dobra}",
            "n_amostras": int(len(y_va)),
            "rmse": m["rmse"],
            "mae": m["mae"],
            "r2": m["r2"],
            "vies": m["vies"],
            "tempo_treino_s": t_treino,
            "tempo_predicao_s": t_pred,
            "observacao": config_str,
        }
        metricas_dobras.append(linha)
        registros_csv.append(linha)

        msg = (
            f"{nome_modelo:<18} dobra {dobra}: RMSE {m['rmse']:.2f} | "
            f"MAE {m['mae']:.2f} | R2 {m['r2']:.4f} | "
            f"treino {t_treino:.1f}s | predicao {t_pred:.1f}s"
        )
        print(msg)
        linhas_txt.append(msg)

        del pipe, X_tr, X_va
        gc.collect()

    df_d = pd.DataFrame(metricas_dobras)
    cols_num = ["rmse", "mae", "r2", "vies", "tempo_treino_s", "tempo_predicao_s"]
    medias = df_d[cols_num].mean()
    dps = df_d[cols_num].std(ddof=0)

    for stat_nome, serie in [("media", medias), ("desvio_padrao", dps)]:
        registros_csv.append({
            "etapa": "cv_resumo",
            "modelo": nome_modelo,
            "dobra_ou_grupo": stat_nome,
            "n_amostras": int(df_d["n_amostras"].mean()),
            "rmse": float(serie["rmse"]),
            "mae": float(serie["mae"]),
            "r2": float(serie["r2"]),
            "vies": float(serie["vies"]),
            "tempo_treino_s": float(serie["tempo_treino_s"]),
            "tempo_predicao_s": float(serie["tempo_predicao_s"]),
            "observacao": config_str,
        })

    resumo_fmt = pd.DataFrame({"media": medias, "desvio_padrao": dps}).T
    linhas_txt.append(f"\nResumo de {nome_modelo}:")
    linhas_txt.append(resumo_fmt[["rmse", "mae", "r2", "tempo_treino_s", "tempo_predicao_s"]].to_string())
    linhas_txt.append(f"Hipotese: {hipotese}\n")
    return float(medias["rmse"]), float(medias["mae"]), float(medias["r2"])


