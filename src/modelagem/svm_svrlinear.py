def sanitizar_dataframe_parquet(df_in):
    """Converte tipos anuláveis do Parquet (Int64, Float64, boolean, pd.NA) para NumPy padrão."""
    df_out = pd.DataFrame(index=df_in.index)
    for col in df_in.columns:
        s = df_in[col]
        if pd.api.types.is_bool_dtype(s):
            df_out[col] = s.astype("float32")
        elif pd.api.types.is_numeric_dtype(s):
            arr = pd.to_numeric(s, errors="coerce").to_numpy(dtype=np.float32, na_value=np.nan)
            arr[~np.isfinite(arr)] = np.nan
            df_out[col] = arr
        else:
            s_obj = s.astype("object")
            s_obj = s_obj.where(pd.notna(s_obj), np.nan)
            df_out[col] = s_obj.apply(lambda v: str(v) if pd.notna(v) else np.nan)
    return df_out


def separar_dev_teste_e_dobras(df_raw, X, y, semente=42, n_dobras=3):
    """
    Usa as colunas de controle CONJUNTO e DOBRA do parquet da equipe quando disponiveis,
    garantindo alinhamento exato com os demais modelos do grupo.
    """
    usou_conjunto = False
    dobras_dev_serie = None

    if "CONJUNTO" in df_raw.columns:
        conj = df_raw["CONJUNTO"].astype(str).str.strip().str.lower()
        mask_teste = conj.str.contains("test")
        mask_dev = ~mask_teste
        if mask_teste.sum() > 0 and mask_dev.sum() > 0:
            X_dev = X.loc[mask_dev].reset_index(drop=True)
            y_dev = y[mask_dev.to_numpy()]
            X_teste = X.loc[mask_teste].reset_index(drop=True)
            y_teste = y[mask_teste.to_numpy()]
            if "DOBRA" in df_raw.columns:
                dobras_dev_serie = df_raw.loc[mask_dev, "DOBRA"].reset_index(drop=True)
            usou_conjunto = True

    if not usou_conjunto:
        idx_all = np.arange(len(X))
        idx_dev, idx_teste = train_test_split(idx_all, test_size=0.20, random_state=semente)
        X_dev = X.iloc[idx_dev].reset_index(drop=True)
        y_dev = y[idx_dev]
        X_teste = X.iloc[idx_teste].reset_index(drop=True)
        y_teste = y[idx_teste]
        if "DOBRA" in df_raw.columns:
            dobras_dev_serie = df_raw.iloc[idx_dev]["DOBRA"].reset_index(drop=True)

    splits_cv = None
    usou_dobra = False
    if dobras_dev_serie is not None:
        s_clean = dobras_dev_serie.dropna().astype(str).str.strip()
        s_clean = s_clean[~s_clean.str.lower().isin({"", "nan", "none", "na", "-1", "teste", "test"})]
        valores_validos = sorted(s_clean.unique().tolist())
        if len(valores_validos) >= 2:
            splits_cv = []
            idx_base = np.arange(len(X_dev))
            s_all = dobras_dev_serie.fillna("").astype(str).str.strip()
            for val_dobra in valores_validos:
                mask_va = (s_all == val_dobra).to_numpy()
                mask_tr = ~mask_va
                if mask_va.sum() > 0 and mask_tr.sum() > 0:
                    splits_cv.append((idx_base[mask_tr], idx_base[mask_va]))
            if len(splits_cv) >= 2:
                usou_dobra = True

    if not usou_dobra:
        kf = KFold(n_splits=n_dobras, shuffle=True, random_state=semente)
        splits_cv = list(kf.split(X_dev))

    info_split = (
        f"Particao: {'coluna CONJUNTO' if usou_conjunto else 'train_test_split(0.20)'} | "
        f"Dobras CV: {'coluna DOBRA (' + str(len(splits_cv)) + ' dobras)' if usou_dobra else 'KFold(' + str(len(splits_cv)) + ')'}"
    )
    return X_dev, X_teste, y_dev, y_teste, splits_cv, info_split


def calcular_metricas(y_true, y_pred):
    diff = np.asarray(y_true, dtype=np.float64) - np.asarray(y_pred, dtype=np.float64)
    return {
        "rmse": float(np.sqrt(np.mean(diff ** 2))),
        "mae": float(np.mean(np.abs(diff))),
        "r2": float(r2_score(y_true, y_pred)),
        "vies": float(np.mean(diff)),
    }


def gerar_linhas_grupos(df_eval, y_true, y_pred, nome_modelo):
    df_tmp = pd.DataFrame({
        "y_true": np.asarray(y_true, dtype=np.float64),
        "y_pred": np.asarray(y_pred, dtype=np.float64),
    }, index=df_eval.index)

    bins = [-np.inf, 0.0001, 400.0, 500.0, 600.0, 700.0, np.inf]
    labels = ["zero", "0-400", "400-500", "500-600", "600-700", "700+"]
    df_tmp["faixa_nota"] = pd.cut(df_tmp["y_true"], bins=bins, labels=labels)

    colunas_grupo = ["faixa_nota"]
    for col in ["SG_UF_PROVA", "TP_ESCOLA", "Q006"]:
        if col in df_eval.columns:
            df_tmp[col] = df_eval[col].fillna("NA").astype(str)
            colunas_grupo.append(col)

    linhas = []
    for ag in colunas_grupo:
        for grp, sub in df_tmp.groupby(ag, observed=False):
            if len(sub) == 0:
                continue
            diff = sub["y_true"] - sub["y_pred"]
            linhas.append({
                "etapa": "teste_grupo",
                "modelo": nome_modelo,
                "dobra_ou_grupo": f"{ag}: {grp}",
                "n_amostras": int(len(sub)),
                "rmse": float(np.sqrt(np.mean(diff ** 2))),
                "mae": float(np.mean(np.abs(diff))),
                "r2": np.nan,
                "vies": float(np.mean(diff)),
                "tempo_treino_s": np.nan,
                "tempo_predicao_s": np.nan,
                "observacao": f"agrupamento={ag}",
            })
    return linhas


def construir_preprocessador_svm(X_df):
    """
    SVMs dependem de distância e produto interno, exigindo imputação e padronização
    (StandardScaler) nas variáveis numéricas e codificação esparsa nas categóricas.
    """
    cols_cat = X_df.select_dtypes(include=["object", "category", "string"]).columns.tolist()
    cols_num = [c for c in X_df.columns if c not in cols_cat]

    transformers = []
    if cols_num:
        transf_num = Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
        ])
        transformers.append(("num", transf_num, cols_num))
    if cols_cat:
        transf_cat = Pipeline([
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=True, dtype=np.float32)),
        ])
        transformers.append(("cat", transf_cat, cols_cat))

    return ColumnTransformer(transformers=transformers, remainder="drop")


